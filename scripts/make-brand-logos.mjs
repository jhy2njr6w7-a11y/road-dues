// Run: npm i --no-save simple-icons && node scripts/make-brand-logos.mjs
// Copies the logo outlines for the app's car brands from Simple Icons (CC0) into src/brand-logos.js,
// so the app ships only these few paths. Brands Simple Icons doesn't have keep the letter badge.
import fs from 'node:fs';
import * as si from 'simple-icons';
import { BRANDS } from '../src/data.js';

const icons = Object.values(si).filter((x) => x && x.title);
const found = {};
for (const b of BRANDS) {
  const m = icons.find((x) => x.title.toLowerCase() === b.toLowerCase());
  if (m) found[b] = m.path;
}
const body = Object.entries(found).map(([b, p]) => `  ${JSON.stringify(b)}: ${JSON.stringify(p)},`).join('\n');
fs.writeFileSync(new URL('../src/brand-logos.js', import.meta.url),
`// Generated by scripts/make-brand-logos.mjs from Simple Icons (CC0-1.0, https://simpleicons.org).
// One-colour logo outlines, 24×24 viewBox. The logos are their makers' trademarks, shown only to
// identify the user's own car. Brands missing here use the letter badge.
export const BRAND_LOGOS = {
${body}
};
`);
console.log(Object.keys(found).length + ' logos: ' + Object.keys(found).join(', '));
